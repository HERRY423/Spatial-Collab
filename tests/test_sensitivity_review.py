def test_selection_source_hash_must_match_pinned_source(factory, monkeypatch):
    project = factory()
    revision, selection_id = setup(project)
    selected = project.get_selection(selection_id)
    selected["source_sha256"] = "0" * 64
    monkeypatch.setattr(project, "get_selection", lambda _: deepcopy(selected))
    with pytest.raises(SpatialError, match="source|Source"):
        sensitivity.run_sensitivity(project, revision, selection_id, [variant()], [2.0], "T", "B")
    assert project.summary()["runs"] == []


def test_late_resource_failure_saves_no_partial_grid_or_revision(factory, monkeypatch):
    project = factory()
    revision, selection_id = setup(project)
    original = sensitivity._evaluate
    calls = 0

    def bounded(*args, **kwargs):
        nonlocal calls
        calls += 1
        if calls == 3:
            raise SpatialError("Synthetic grid resource limit")
        return original(*args, **kwargs)

    monkeypatch.setattr(sensitivity, "_evaluate", bounded)
    with pytest.raises(SpatialError, match="resource limit"):
        sensitivity.run_sensitivity(project, revision, selection_id, [variant()], [2.0, 5.0], "T", "B")
    assert project.summary()["runs"] == []
    assert project.summary()["revision_count"] == 1
    assert project.context()["latest_proposal_id"] is None


def test_historical_grid_replays_actual_cells_without_counterfactual_revision(factory):
    project = factory()
    revision, selection_id = setup(project)
    proposal = project.propose_revision(revision, selection_id, {"region": "synthetic fixture"}, "synthetic test")
    head = project.apply_revision(proposal["proposal_id"], revision, "Synthetic test driver", True)["revision_id"]
    result = sensitivity.run_sensitivity(project, revision, selection_id, [variant()], [2.0], "T", "B")
    assert result["stale"] and project.summary()["head_revision"] == head
    bundle = Path(project.export_bundle(result["run_id"])["export_path"])
    source_cells = project.cells(revision)
    assert json.loads((bundle / "base_cells.json").read_text()) == source_cells
    assert json.loads((bundle / "target_cells.json").read_text()) == source_cells
    before = {path.name: path.read_bytes() for path in bundle.iterdir()}
    assert verify_bundle(bundle)["recompute_matches"]
    assert {path.name: path.read_bytes() for path in bundle.iterdir()} == before


def _rewrite(folder, name, value):
    content = (json.dumps(value, sort_keys=True, separators=(",", ":")) + "\n").encode()
    (folder / name).write_bytes(content)
    manifest = json.loads((folder / "manifest.json").read_text())
    manifest["files"][name] = {"sha256": hashlib.sha256(content).hexdigest(), "bytes": len(content)}
    (folder / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")


def test_rehashed_claim_of_human_approval_is_not_a_matching_recomputation(factory):
    project = factory()
    result = run(project)
    bundle = Path(project.export_bundle(result["run_id"])["export_path"])
    saved = json.loads((bundle / "result.json").read_text())
    saved["researcher_approval"] = "APPROVED"  # adversarial fixture, never a real attribution
    _rewrite(bundle, "result.json", saved)
    provenance = json.loads((bundle / "provenance.json").read_text())
    provenance["run_sha256"] = _hash(saved)
    _rewrite(bundle, "provenance.json", provenance)
    receipt = verify_bundle(bundle)
    assert receipt["integrity_verified"] and not receipt["recompute_matches"]
    assert "researcher_approval" in receipt["mismatched_fields"]
