@pytest.fixture
def factory(tmp_path):
    def create(scope=None, suffix="project"):
        metadata = {"name": "synthetic sensitivity review", "slice_id": "s", "coordinate_system": "s-xy",
                    "units": "micrometer", "source_kind": "synthetic", "panel_genes": ["G"],
                    "import_scope": scope if scope is not None else {
                        "kind": "spatial_window", "units": "micrometer", "sampling": "none",
                        "bounds": [-10, -10, 40, 40], "selected_observation_count": 4,
                        "source_observation_count": 100,
                        "selection_rule": "all cell centroids with xmin <= x <= xmax and ymin <= y <= ymax"}}
        return Project.create(tmp_path / suffix, [
            {"cell_id": "source", "x": 0, "y": 0, "label": "T", "counts": {"G": 2}},
            {"cell_id": "near_target", "x": 1, "y": 0, "label": "B", "counts": {}},
            {"cell_id": "far_target", "x": 20, "y": 0, "label": "B", "counts": {}},
            {"cell_id": "edge_other", "x": 39, "y": 0, "label": "O", "counts": {}}], metadata)
    return create


def setup(project, ids=None):
    revision = project.summary()["head_revision"]
    selection = project.set_selection(revision, cell_ids=ids or ["source"])
    return revision, selection["selection_id"]


def variant(name="relabel_near", ids=None, changes=None):
    return {"name": name, "cell_ids": ids or ["near_target"], "changes": changes or {"label": "O"},
            "rationale": "Synthetic alternative assumption; no human decision implied"}


def run(project, variants=None, radii=None, ids=None, **kwargs):
    revision, selection = setup(project, ids)
    return sensitivity.run_sensitivity(project, revision, selection, variants or [variant()],
                                       radii or [2.0], "T", "B", **kwargs)


def test_variants_restart_from_baseline_and_off_roi_neighbors_remain_eligible(factory):
    project = factory()
    before = deepcopy(project.cells())
    result = run(project, [variant(), variant("exclude_far", ["far_target"], {"included": False})])
    relabel, exclusion = result["results"]
    assert relabel["before"] == exclusion["before"]
    assert relabel["after"]["observed_fraction"] == 0
    assert exclusion["after"]["observed_fraction"] == 1  # near target did not inherit variant one's relabel
    assert exclusion["after"]["null_fraction"] == 0.5
    assert relabel["changed_in_analysis_roi"] == exclusion["changed_in_analysis_roi"] == 0
    assert relabel["actual_changed_count"] == exclusion["actual_changed_count"] == 1
    assert project.cells() == before
    assert project.context()["latest_proposal_id"] is None
    assert project.summary()["revision_count"] == 1
    assert result["base_revision"] == result["target_revision"]
    assert result["researcher_approval"] == "NOT_REQUESTED_HYPOTHESIS_ONLY"


